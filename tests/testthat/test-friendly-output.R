test_that('interval displays retain numerical values and identify units', {
  p <- proportion_ci(40,100)
  before <- serialize(p,NULL)
  text <- capture.output(returned <- print(p))
  expect_identical(serialize(p,NULL), before)
  expect_identical(returned,p)
  expect_true(any(grepl('Wilson confidence interval for proportion',text)))
  expect_true(any(grepl('Successes: 40',text)))
  expect_true(any(grepl('Trials: 100',text)))
  expect_true(any(grepl('Estimate: 40%',text,fixed=TRUE)))
  expect_equal(unname(coef(p)),.4)
  expect_equal(as.numeric(confint(p)),c(p$lower,p$upper))
  tab <- as.data.frame(p)
  expect_identical(class(tab),'data.frame')
  expect_equal(tab$estimate,.4)
  expect_equal(tab$lower,p$lower)
  expect_error(confint(p,level=.9),'Rerun')
  expect_error(confint(p,parm='other'),'single stored')
  expect_error(print(p,digits=0),'digits')
  expect_true(any(grepl('estimate',capture.output(print(p['estimate'])),ignore.case=TRUE)))
})
test_that('difference direction and percentage points are explicit', {
  d <- proportion_difference_ci(40,100,25,100)
  text <- capture.output(print(d))
  expect_true(any(grepl('group 1 minus group 2',text,fixed=TRUE)))
  expect_true(any(grepl('percentage points',text,fixed=TRUE)))
  expect_equal(d$estimate,.15)
  a <- mean_difference_ci(1:10,3:14)
  expect_true(any(grepl('group 1 minus group 2',capture.output(print(a)),fixed=TRUE)))
  expect_equal(a$estimate,mean(1:10)-mean(3:14))
  v <- sd_ci(1:10)
  expect_true(any(grepl('standard deviation',capture.output(print(v)),fixed=TRUE)))
  expect_equal(v$estimate,sd(1:10))
})
